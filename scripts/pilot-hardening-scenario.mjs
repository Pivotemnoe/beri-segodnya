import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import { generateCode } from "../backend/utils/id.mjs";
import { hasPartnerPermission, parseCookies } from "../backend/services/authService.mjs";

export async function runPilotHardeningScenario(port, request, { adminCookie, partnerCookie, dbFile, suffix }) {
  assert.equal(parseCookies("a=one%3Dtwo; a=last; bare").a, "last");
  assert.equal(parseCookies("a=one%3Dtwo").a, "one=two");
  assert.throws(() => parseCookies("__Host-bs_session=%; bs_session=valid"), (error) => error.status === 400);
  assert.equal(hasPartnerPermission({ role: "partner", user_role: "unknown" }, "offers:write"), false);
  const existing = new Set(Array.from({ length: 9000 }, (_, i) => `BS-${i + 1000}`));
  const randomInt = crypto.randomInt;
  try {
    crypto.randomInt = (...args) => args.length === 2 ? args[0] : 0;
    assert.equal(generateCode(existing), "BS-100000", "Exhausted four-digit range must expand, never collide");
    existing.delete("BS-9999");
    assert.equal(generateCode(existing), "BS-9999", "Forced collisions must find the remaining unique code");
  } finally { crypto.randomInt = randomInt; }

  const admin = (route, options = {}) => request(port, route, { auth: "adminBasic", cookie: adminCookie, ...options });
  const owner = (route, options = {}) => request(port, route, { auth: "partnerBasic", cookie: partnerCookie, ...options });
  const createOffer = async (partnerId, addressId) => {
    const result = await admin("/api/admin/offers", { method: "POST", body: { partnerId, addressId, title: "Тестовая партия", category: "lunch", price: 199, oldPrice: 299, contents: "Тестовый состав", allergens: "Тестовые аллергены", pickupWindow: "00:00–23:59", totalQuantity: 8, status: "active" } });
    assert.equal(result.status, 201);
    return result.json.data;
  };
  const offer = await createOffer("partner-1", "partner-1-address-1");
  const input = { offerId: offer.id, customerName: "Тестовый покупатель", customerPhone: "9001234567", personalDataConsent: true, requestId: crypto.randomUUID() };
  const first = await request(port, "/api/public/bookings", { method: "POST", body: input });
  assert.equal(first.status, 201);
  const token = first.json.data.publicToken;
  const original = (await request(port, `/api/public/bookings/${token}`)).json.data;
  assert.equal(original.price, 199);
  assert.equal(original.termsVerified, true);
  assert.equal((await request(port, first.json.data.bookingUrl)).status, 200);
  assert.equal((await request(port, first.json.data.bookingUrl.replace("booking-view", "%62ooking-view"))).status, 200);
  const duplicate = await request(port, "/api/public/bookings", { method: "POST", body: input });
  assert.equal(duplicate.json.data.bookingId, first.json.data.bookingId, "A lost-response retry created a second booking");
  const conflict = await request(port, "/api/public/bookings", { method: "POST", body: { ...input, customerName: "Другой тестовый покупатель" } });
  assert.equal(conflict.status, 409);
  assert.equal(conflict.json.error.code, "BOOKING_REQUEST_CONFLICT");
  assert.equal((await request(port, "/api/public/bookings", { method: "POST", body: { ...input, requestId: input.requestId + "trailing" } })).status, 400, "Request ID was silently truncated");
  const update = await owner(`/api/partner/offers/${offer.id}`, { method: "PATCH", body: { title: "Новая тестовая партия", price: 299, oldPrice: 399, contents: "Другой состав", pickupWindow: "01:00–22:00" } });
  assert.equal(update.status, 200);
  await owner("/api/partner/profile", { method: "PATCH", body: { name: "Новое тестовое название" } });
  const address = await owner("/api/partner/addresses/partner-1-address-1", { method: "PATCH", body: { address: "Армавир, другой тестовый адрес" } });
  assert.equal(address.status, 200);
  const after = (await request(port, `/api/public/bookings/${token}`)).json.data;
  for (const key of ["offerTitle", "price", "contents", "allergens", "pickupWindow", "address", "partnerName", "expiresAt"]) assert.equal(after[key], original[key], `Booking contract changed: ${key}`);
  const again = await request(port, "/api/public/bookings", { method: "POST", body: input });
  assert.equal(again.json.data.pickupWindow, original.pickupWindow, "Retry did not return the frozen pickup window");
  const ownerBookings = (await owner("/api/partner/bookings")).json.data;
  const record = ownerBookings.find((row) => row.id === first.json.data.bookingId);
  assert.equal(record.price, 199);
  assert.equal(record.request_key_hash, undefined);
  const remaining = (await owner("/api/partner/offers")).json.data.find((row) => row.id === offer.id).remaining_quantity;
  assert.equal(remaining, 7, "Retries deducted more than one unit");

  const password = crypto.randomBytes(18).toString("base64url");
  const user = await admin("/api/admin/partners/partner-1/users", { method: "POST", body: { name: "Тестовый продавец", login: `seller-${suffix}`, password, role: "seller", status: "active" } });
  assert.equal(user.status, 201);
  const login = await request(port, "/api/partner/auth/login", { method: "POST", body: { login: `seller-${suffix}`, password } });
  assert.equal(login.json.data.userRole, "seller");
  let sellerCookie = login.headers["set-cookie"][0];
  const blocked = await request(port, "/api/partner/bookings", { cookie: sellerCookie });
  assert.equal(blocked.status, 403, "Seller skipped mandatory first password rotation");
  const permanent = crypto.randomBytes(18).toString("base64url");
  const changed = await request(port, "/api/partner/auth/change-password", { method: "POST", cookie: sellerCookie, body: { currentPassword: password, newPassword: permanent, confirmPassword: permanent } });
  assert.equal(changed.status, 200);
  sellerCookie = changed.headers["set-cookie"][0];
  const seller = (route, options = {}) => request(port, route, { cookie: sellerCookie, ...options });
  for (const route of ["/api/partner/profile", "/api/partner/offers", "/api/partner/addresses", "/api/partner/offer-templates"]) assert.equal((await seller(route)).status, 403, `Seller gained unnecessary read scope: ${route}`);
  for (const route of ["/api/partner/offers", "/api/partner/uploads", "/api/partner/offer-templates"]) assert.equal((await seller(route, { method: "POST", body: {} })).status, 403, `Seller gained write scope: ${route}`);
  const own = await seller("/api/partner/bookings");
  assert.equal(own.status, 200);
  assert.ok(own.json.data.some((row) => row.id === record.id));
  assert.ok(own.json.data.every((row) => !row.customer_phone && !row.public_token && !row.consent_version), "Seller can see unnecessary personal data or bearer links");
  const cancel = await seller(`/api/partner/bookings/${record.id}/status`, { method: "PATCH", body: { status: "cancelled" } });
  assert.equal(cancel.status, 403);
  const foreignOffer = await createOffer("partner-2", "partner-2-address-1");
  const foreign = await request(port, "/api/public/bookings", { method: "POST", body: { ...input, offerId: foreignOffer.id, requestId: crypto.randomUUID() } });
  assert.equal(foreign.status, 201);
  assert.equal((await seller(`/api/partner/bookings/${foreign.json.data.bookingId}/status`, { method: "PATCH", body: { status: "issued" } })).status, 404, "Seller could issue another partner's booking");
  assert.ok(!(await seller("/api/partner/bookings")).json.data.some((row) => row.id === foreign.json.data.bookingId));
  const issued = await seller(`/api/partner/bookings/${record.id}/status`, { method: "PATCH", body: { status: "issued" } });
  assert.equal(issued.status, 200);
  assert.equal((await seller(`/api/partner/bookings/${record.id}/status`, { method: "PATCH", body: { status: "no_show" } })).status, 409, "Seller could rewrite a completed handover");
  assert.equal((await request(port, `/api/public/bookings/${token}`)).json.data.status, "issued");
  const today = await owner("/api/partner/dashboard?period=today");
  assert.equal(today.json.data.estimatedRevenue, 199, "Issued amount used the edited offer price");
  assert.equal((await owner("/api/partner/dashboard?period=invalid")).status, 400);
  const persisted = JSON.parse(fs.readFileSync(dbFile, "utf8"));
  assert.ok(persisted.auditLog.some((entry) => entry.action === "set_booking_status" && entry.entity_id === record.id && entry.actor_id === user.json.data.id), "Handover audit lacks the staff identity");
  persisted.bookings.push({ id: "legacy-test-booking", code: "BS-LEGACY", offer_id: offer.id, partner_id: "partner-1", address_id: "partner-1-address-1", status: "issued", public_token: "legacy-test-token", created_at: persisted.bookings[0].created_at, updated_at: persisted.bookings[0].updated_at });
  fs.writeFileSync(dbFile, JSON.stringify(persisted), { mode: 0o600 });
  const legacy = (await request(port, "/api/public/bookings/legacy-test-token")).json.data;
  assert.equal(legacy.price, null);
  assert.equal(legacy.termsVerified, false);
  const legacyStats = (await owner("/api/partner/dashboard?period=all")).json.data;
  assert.equal(legacyStats.estimatedRevenue, 199);
  assert.equal(legacyStats.unknownIssuedAmountsCount, 1);

  const correctionInput = { status: "no_show", expectedStatus: "issued", reason: "Тестовая ошибочная отметка выдачи" };
  assert.equal((await seller(`/api/admin/bookings/${record.id}/correction`, { method: "PATCH", body: correctionInput })).status, 403);
  assert.equal((await admin(`/api/admin/bookings/${record.id}/correction`, { method: "PATCH", body: { ...correctionInput, reason: "нет" } })).status, 400);
  const corrected = await admin(`/api/admin/bookings/${record.id}/correction`, { method: "PATCH", body: correctionInput });
  assert.equal(corrected.status, 200);
  assert.equal(corrected.json.data.corrections.length, 1);
  const audit = await admin("/api/admin/audit-log");
  const correctionAudit = audit.json.data.find((row) => row.action === "correct_booking_status" && row.referenceLabel === record.code);
  const handoverAudit = audit.json.data.find((row) => row.action === "set_booking_status" && row.referenceLabel === record.code && row.status === "issued");
  assert.equal(handoverAudit?.actorName, "Тестовый продавец", "Admin audit does not name the actual staff user");
  assert.equal(correctionAudit?.actorName, null, "Missing actor identity was fabricated");
  assert.equal(correctionAudit?.previousStatus, "issued");
  assert.equal(correctionAudit?.status, "no_show");
  assert.equal(correctionAudit?.reason, correctionInput.reason);
  assert.equal((await owner("/api/admin/audit-log")).status, 403, "Partner can read the administrative audit log");
  const auditFixtures = JSON.parse(fs.readFileSync(dbFile, "utf8"));
  const fixtureBase = { actor_role: "admin", actor_id: "private-actor", entity_type: "contactRequests", entity_id: "deleted-test-contact", created_at: record.created_at };
  auditFixtures.auditLog.push(
    { ...fixtureBase, id: "audit-malformed-test", action: "patch_contactRequests", metadata_json: "{broken" },
    { ...fixtureBase, id: "audit-secret-test", action: "patch_contactRequests", metadata_json: JSON.stringify({ status: "unknown-private-status", actorName: "never-expose-metadata-name", password: "never-expose-test-password", token: "never-expose-test-token", reason: "never-expose-unrelated-reason", message: "never-expose-test-message" }) }
  );
  fs.writeFileSync(dbFile, JSON.stringify(auditFixtures), { mode: 0o600 });
  const safeAudit = await admin("/api/admin/audit-log");
  assert.equal(safeAudit.status, 200, "Malformed old audit metadata stopped the endpoint");
  assert.ok(!safeAudit.text.includes("never-expose") && !safeAudit.text.includes("private-actor") && !safeAudit.text.includes("deleted-test-contact"), "Audit leaked internal or unapproved data");
  for (const row of safeAudit.json.data.slice(-2)) {
    assert.equal(row.entityType, "contact_request");
    assert.equal(row.referenceLabel, null);
    assert.equal(row.previousStatus, null);
    assert.equal(row.status, null);
    assert.equal(row.reason, null);
    assert.equal(row.actorName, null);
  }
  assert.equal((await admin(`/api/admin/bookings/${record.id}/correction`, { method: "PATCH", body: correctionInput })).status, 409, "Stale correction was accepted");
  assert.equal((await owner("/api/partner/offers")).json.data.find((row) => row.id === offer.id).remaining_quantity, 7, "Correction invented a physical stock return");
  assert.equal((await owner("/api/partner/dashboard?period=today")).json.data.estimatedRevenue, 0);
  const foreignId = foreign.json.data.bookingId;
  assert.equal((await admin(`/api/admin/bookings/${foreignId}/status`, { method: "PATCH", body: { status: "cancelled" } })).status, 200);
  await admin(`/api/admin/offers/${foreignOffer.id}`, { method: "PATCH", body: { remainingQuantity: 0 } });
  const reinstate = { status: "issued", expectedStatus: "cancelled", reason: "Тестовая ошибочная отмена после сверки" };
  const noStock = await admin(`/api/admin/bookings/${foreignId}/correction`, { method: "PATCH", body: reinstate });
  assert.equal(noStock.status, 409);
  assert.equal(noStock.json.error.code, "CORRECTION_NO_STOCK");
  await admin(`/api/admin/offers/${foreignOffer.id}`, { method: "PATCH", body: { remainingQuantity: 8 } });
  assert.equal((await admin(`/api/admin/bookings/${foreignId}/correction`, { method: "PATCH", body: reinstate })).status, 200);
  assert.equal((await admin("/api/admin/offers")).json.data.find((row) => row.id === foreignOffer.id).remaining_quantity, 7);
  assert.equal((await admin(`/api/admin/bookings/${record.id}/correction`, { method: "PATCH", body: { status: "created", expectedStatus: "no_show", reason: reinstate.reason } })).status, 400, "Correction reopened a terminal booking");
  console.log("Pilot hardening passed: snapshot, legacy amounts, unique codes, idempotent retry, seller permissions/isolation and audited correction");
}
