import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { Script, createContext } from "node:vm";
import { runTextAssetChecks } from "./text-assets-checks.mjs";

export function runClientPwaChecks(root) {
  runTextAssetChecks();
  const source = fs.readFileSync(path.join(root, "public/pwa-shell.js"), "utf8");
  const stored = new Map();
  const window = {};
  const context = createContext({ window, URL, location: { origin: "https://example.test" }, localStorage: { getItem: key => stored.get(key) ?? null, setItem: (key, value) => stored.set(key, value) } });
  const helpers = source.slice(source.indexOf('  const guestKey ='), source.indexOf('  const shell ='));
  const { bookingPath, guestLinks, appHref } = new Script(`${helpers}\n({bookingPath,guestLinks,appHref})`).runInContext(context);
  const token = "booking-view-" + "a".repeat(40), link = `/booking/${token}`;
  assert.equal(bookingPath(link + "?app=1"), link);
  for (const invalid of ["https://evil.test" + link, "javascript:alert(1)", "/booking/BS-1234", "/api/customer/bookings", null, {}, "x".repeat(301)]) assert.equal(bookingPath(invalid), "");
  window.bsRememberGuestBooking(link); window.bsRememberGuestBooking(link);
  assert.equal(guestLinks().length, 1, "Guest bookmark duplicates were stored");
  window.bsRememberGuestBooking("https://evil.test" + link);
  assert.equal(guestLinks().length, 1, "External guest bookmark was accepted");
  for (let i = 0; i < 30; i++) window.bsRememberGuestBooking(`/booking/booking-view-${String(i).padStart(40, "0")}`);
  assert.equal(guestLinks().length, 20, "Guest bookmark storage is unbounded");
  assert.ok([...stored.values()].every(value => !value.includes('"code"') && !value.includes('"phone"') && !value.includes('"email"')), "Private booking/account data was stored");
  stored.set("bs_pwa_guest_links_v1", "{bad json"); assert.equal(guestLinks().length, 0);
  stored.set("bs_pwa_guest_links_v1", JSON.stringify([link, link, {}, "https://evil.test" + link])); assert.equal(guestLinks().length, 1);
  assert.equal(appHref("https://example.test/#offers"), "/app");
  assert.equal(appHref("/customer"), "/app/profile");
  assert.equal(appHref("/partner/dashboard?tab=codes"), "/partner/dashboard?tab=codes&app=1");
  assert.equal(appHref("/partners#partner-application"), "/partners?app=1#partner-application");
  assert.equal(appHref("https://evil.test/customer"), "https://evil.test/customer");
  assert.equal(appHref("/downloads/app.apk"), "/downloads/app.apk");
  const paths = ["/app", "/app/bookings", "/app/profile", "/app/partners"];
  const events = new Map(), changed = [], bodyClasses = new Set();
  const views = paths.map(path => ({ dataset: { pwaView: path }, hidden: path !== "/app", querySelector: () => ({ textContent: path, setAttribute() {}, focus() {} }) }));
  const links = paths.map(path => {
    const attributes = new Map(); let href = "https://example.test" + path;
    return { get href() { return href; }, set href(value) { href = new URL(value, "https://example.test").href; }, target: "", hasAttribute: name => attributes.has(name), setAttribute: (name, value) => attributes.set(name, value), removeAttribute: name => attributes.delete(name), attributes };
  });
  Object.assign(context.location, { href: "https://example.test/app", pathname: "/app" });
  Object.assign(window, { scrollY: 0, scrollTo() {}, addEventListener: (name, handler) => events.set(name, handler), dispatchEvent: event => changed.push(event.detail.pathname) });
  context.CustomEvent = class { constructor(type, options) { this.type = type; this.detail = options.detail; } };
  context.history = { pushState(_state, _title, value) { const url = new URL(value, context.location.origin); context.location.href = url.href; context.location.pathname = url.pathname; } };
  context.document = { body: { classList: { toggle(name, enabled) { enabled ? bodyClasses.add(name) : bodyClasses.delete(name); } } }, querySelector: () => ({ dataset: {} }), querySelectorAll: selector => selector === "[data-pwa-view]" ? views : links, addEventListener: (name, handler) => events.set(name, handler) };
  context.fetch = () => { throw new Error("Tab switch must not fetch a document"); };
  const router = source.slice(source.indexOf("  const shell ="), source.indexOf("  const viewport ="));
  const { navigate } = new Script(`${router}\n({navigate})`).runInContext(context);
  assert.equal(navigate("/app/profile"), true);
  assert.deepEqual(views.map(view => view.hidden), [true, true, false, true]);
  assert.ok(bodyClasses.has("page-pwa-profile"));
  assert.equal(links[2].attributes.get("aria-current"), "page");
  assert.equal(navigate("https://evil.test/app"), false);
  assert.equal(navigate("/partner/dashboard?app=1"), false, "Private workspace must use real server navigation");
  let prevented = false;
  events.get("click")({ target: { closest: () => links[3] }, button: 0, preventDefault() { prevented = true; } });
  assert.equal(prevented, true); assert.equal(context.location.pathname, "/app/partners");
  assert.deepEqual(views.map(view => view.hidden), [true, true, true, false]);
  prevented = false;
  events.get("click")({ target: { closest: () => links[0] }, button: 0, ctrlKey: true, preventDefault() { prevented = true; } });
  assert.equal(prevented, false, "Modified clicks must keep normal browser behaviour");
  context.location.pathname = "/app/bookings"; events.get("popstate")();
  assert.deepEqual(views.map(view => view.hidden), [true, false, true, true]);
  assert.deepEqual(changed, ["/app/profile", "/app/partners", "/app/bookings"]);
  assert.ok(source.includes('cache: "no-store"') && source.includes('Promise.allSettled') && source.includes('AbortController'), "PWA history does not use bounded fresh server requests");
  assert.ok(source.includes('Не все брони загрузились') && !source.includes('localStorage.removeItem'), "Temporary network failures erase guest bookmarks");
  assert.ok(source.includes('if (!authenticated || tourSeen()') && source.includes('dialog.showModal()') && source.includes('dialog.addEventListener("close"') && source.includes('bs-customer-change'), "Optional authenticated onboarding is incomplete");
  const publicSource = fs.readFileSync(path.join(root, "server.mjs"), "utf8");
  const customerSource = fs.readFileSync(path.join(root, "public/customer.js"), "utf8");
  assert.ok(customerSource.includes("refreshPending") && customerSource.includes("revision !== accountRevision") && customerSource.includes("ownerId !== window.bsCustomer?.id"), "Shared authentication must not resurrect stale signed-out profile/history");
  assert.ok(publicSource.includes('if (!bookingForm.dataset.bookingOwner) window.bsRememberGuestBooking?.(result.bookingUrl)'), "Account bookings are copied into guest history");
}
